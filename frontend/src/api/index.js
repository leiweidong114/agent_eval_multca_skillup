import axios from 'axios'

const http = axios.create({ baseURL: '/api', timeout: 100000 })
const prism = axios.create({ baseURL: '/prism/api', timeout: 100000 })
const data = (request) => request.then((response) => response.data)

export const fetchHealth = () => data(http.get('/health'))
export const fetchAgents = () => data(http.get('/agents'))
export const fetchModels = () => data(http.get('/models'))
export const testAgentAvailability = (agent) => data(http.post(`/agents/${encodeURIComponent(agent)}/test`))
export const testModelAvailability = (model, profile) => data(http.post('/models/test', { model, profile }))
export const fetchModelConfig = () => data(http.get('/model-config'))
export const fetchDatabaseHealth = () => data(http.get('/database/health'))
export const fetchSkills = () => data(http.get('/skills'))
export const fetchSkill = (name) => data(http.get(`/skills/${encodeURIComponent(name)}`))
export const fetchSkillFile = (name, path) => data(http.get(`/skills/${encodeURIComponent(name)}/files/${path.split('/').map(encodeURIComponent).join('/')}`))
export const fetchSkillCases = (name) => data(http.get(`/skills/${encodeURIComponent(name)}/cases`))
export const triggerRun = (payload) => data(http.post('/run', payload))
export const triggerValidate = (payload) => data(http.post('/validate', payload))
export const fetchJobs = () => data(http.get('/jobs'))
export const fetchJob = (id) => data(http.get(`/jobs/${id}`))
export const createBatchRun = (payload) => data(http.post('/batches', payload))
export const fetchBatches = () => data(http.get('/batches'))
export const fetchBatch = (id) => data(http.get(`/batches/${encodeURIComponent(id)}`))
export const cancelJob = (id) => data(http.post(`/jobs/${id}/cancel`))
export const fetchCapacity = () => data(http.get('/capacity'))
export const fetchRuns = () => data(http.get('/runs'))
export const fetchRun = (runId) => data(http.get(`/runs/${runId}`))
export const uploadSkill = (name, archive) => {
  const form = new FormData()
  form.append('name', name)
  form.append('archive', archive)
  return data(http.post('/skills/upload', form))
}
export const fetchSkillVersions = () => data(http.get('/skills/versions'))
export const deleteSkillVersion = (name, version) => data(http.delete(`/skills/${name}/versions/${version}`))
export const fetchRetention = () => data(http.get('/privacy/retention'))
export const cleanupRetention = () => data(http.post('/privacy/retention/cleanup', { confirm: true }))
export const fetchSchematicExample = () => data(http.get('/schematic/example'))
export const generateSchematic = (payload) => data(http.post('/schematic/generate', payload))
export const fetchSchematicProject = (id) => data(http.get(`/schematic/projects/${id}`))

export const fetchPrismDashboard = () => data(prism.get('/dashboard'))
export const fetchBenchmarks = () => data(prism.get('/benchmarks'))
export const fetchBenchmark = (id) => data(prism.get(`/benchmarks/${encodeURIComponent(id)}`))
export const fetchBenchmarkItems = (id, limit = 100) => data(prism.get(`/benchmarks/${encodeURIComponent(id)}/items`, { params: { limit } }))
export const importBenchmark = (payload) => data(prism.post('/benchmarks/import', payload))
export const fetchProviders = () => data(prism.get('/providers'))
export const ensureAutoProvider = (payload) => data(prism.post('/providers/auto', payload))
export const testProvider = (id) => data(prism.post(`/providers/${id}/test`))
export const fetchProtocols = () => data(prism.get('/protocols'))
export const createExperiment = (payload) => data(prism.post('/experiments', payload))
export const fetchExperiments = () => data(prism.get('/experiments'))
export const fetchExperiment = (id) => data(prism.get(`/experiments/${id}`))
export const fetchExperimentResults = (id, limit = 1000) => data(prism.get(`/experiments/${id}/results`, { params: { limit } }))
export const fetchExperimentComparison = (id) => data(prism.get(`/experiments/${id}/comparison`))
export const cancelExperiment = (id) => data(prism.post(`/experiments/${id}/cancel`))

export { http, prism }
export default http
